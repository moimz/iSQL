import Foundation

extension SQLSyntax {
	/// Oracle: "이름" (따옴표 없는 이름은 대문자로 바뀐다), '글자' 는 '' 로 (\ 는 그냥 글자), -- 와 /* */ 주석.
	/// PL/SQL 블록(BEGIN … END;)은 / 줄이나 글 끝에서 끝난다
	static let oracle: SQLSyntax = {
		let keywords = """
		SELECT FROM WHERE AND OR NOT IN IS NULL LIKE BETWEEN EXISTS AS ON JOIN LEFT RIGHT INNER OUTER FULL CROSS NATURAL USING \
		GROUP BY ORDER ASC DESC NULLS FIRST LAST HAVING DISTINCT UNIQUE UNION ALL MINUS INTERSECT INSERT INTO VALUES UPDATE SET \
		DELETE MERGE MATCHED CREATE ALTER DROP TRUNCATE RENAME TABLE VIEW INDEX SEQUENCE SYNONYM TRIGGER PROCEDURE FUNCTION \
		PACKAGE BODY TYPE USER SCHEMA PRIMARY KEY FOREIGN REFERENCES CONSTRAINT DEFAULT CHECK CASCADE PURGE COMMENT GRANT REVOKE \
		CASE WHEN THEN ELSE END WITH BEGIN DECLARE EXCEPTION RETURN RETURNING IS LOOP FOR WHILE IF ELSIF COMMIT ROLLBACK SAVEPOINT \
		FETCH NEXT ROWS ONLY OFFSET ROWNUM ROWID LEVEL CONNECT PRIOR START PIVOT UNPIVOT OVER PARTITION GENERATED IDENTITY ALWAYS \
		EXPLAIN PLAN DUAL SYSDATE SYSTIMESTAMP
		""".split(separator: " ").map(String.init)
		let functions = """
		COUNT SUM AVG MIN MAX LISTAGG NVL NVL2 COALESCE NULLIF DECODE GREATEST LEAST ABS CEIL FLOOR ROUND TRUNC MOD POWER SQRT \
		LENGTH LENGTHB SUBSTR INSTR UPPER LOWER INITCAP LPAD RPAD LTRIM RTRIM TRIM REPLACE TRANSLATE CONCAT REGEXP_LIKE \
		REGEXP_SUBSTR REGEXP_REPLACE REGEXP_INSTR TO_CHAR TO_NUMBER TO_DATE TO_TIMESTAMP TO_CLOB CAST ADD_MONTHS MONTHS_BETWEEN \
		LAST_DAY NEXT_DAY EXTRACT CURRENT_DATE CURRENT_TIMESTAMP SYS_GUID USER UID ROW_NUMBER RANK DENSE_RANK LAG LEAD \
		FIRST_VALUE LAST_VALUE NTILE JSON_VALUE JSON_QUERY JSON_OBJECT JSON_ARRAY JSON_EXISTS JSON_TABLE HEXTORAW RAWTOHEX \
		DBMS_LOB.SUBSTR DBMS_LOB.GETLENGTH
		""".split(separator: " ").map(String.init)
		let types = ["VARCHAR2", "NVARCHAR2", "CHAR", "NCHAR", "NUMBER", "INTEGER", "FLOAT", "BINARY_FLOAT", "BINARY_DOUBLE", "DATE",
		             "TIMESTAMP", "INTERVAL", "CLOB", "NCLOB", "BLOB", "BFILE", "RAW", "LONG", "BOOLEAN", "JSON", "VECTOR", "XMLTYPE",
		             "TRUE", "FALSE", "ZONE", "LOCAL", "TIME"]
		let any: [SQLKind: ServerVersion] = [.oracle: ServerVersion(0)]
		var s = SQLSyntax(identifierQuote: 0x22, stringQuotes: [0x27], backslashEscapes: false, hashComments: false, delimiterCommand: false,
		                  highlightKeywords: Set(keywords + types + ["COUNT", "SUM", "AVG", "MIN", "MAX"]), completionKeywords: keywords,
		                  functions: functions.map { SQLFunction(name: $0, since: any) },
		                  reservedWords: Set(keywords + ["ACCESS", "AUDIT", "COLUMN", "FILE", "LOCK", "MODE", "NUMBER", "RAW", "SESSION",
		                                                 "SIZE", "TO", "UID", "VARCHAR", "VARCHAR2", "DATE", "CHAR", "LONG", "OPTION"]))
		s.plsqlBlocks = true
		return s
	}()
}
